import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createClassifier } from "../src/core/classify";
import { registry } from "../src/core/registry";
const cls = createClassifier(registry);
const walk = (d: string): string[] => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(process.argv[2]!).sort();
let seed = 42; const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2 ** 31) / 2 ** 31);
const bySignal: Record<string, any[]> = {}; const near: any[] = []; const neg: any[] = [];
const kw = /\b(claude|copilot|codex|cursor|devin|jules|aider|gemini|opencode|capy|junie|amp|openhands|windsurf|gpt|llm|ai-generated|generated by ai)\b/i;
for (const f of files) {
  const d = JSON.parse(readFileSync(f, "utf8"));
  const repo = d.repo.fullName;
  for (const c of d.commits.items) {
    if (cls.isIgnoredCommit(c)) continue;
    const m = cls.commit(c);
    const item = { type: "commit", repo, url: c.url, message: c.message.slice(0, 20000), authorName: c.authorName, authorEmail: c.authorEmail, authorLogin: c.authorLogin, committerName: c.committerName, committerEmail: c.committerEmail, committerLogin: c.committerLogin };
    if (m.length) { const k = m[0]!.agentId + "|" + m[0]!.kind; (bySignal[k] ??= []).push(item); }
    else if (kw.test(c.message + " " + c.authorName + " " + c.authorEmail)) near.push(item);
    else if (rnd() < 0.002) neg.push(item);
  }
  for (const p of d.pulls.items) {
    if (cls.isIgnoredPull(p)) continue;
    const m = cls.pull(p);
    const item = { type: "pull", repo, url: p.url, title: p.title, body: (p.body ?? "").slice(0, 20000), authorLogin: p.authorLogin, branch: p.branch };
    if (m.length) { const k = m[0]!.agentId + "|" + m[0]!.kind; (bySignal[k] ??= []).push(item); }
    else if (kw.test(p.branch + " " + p.authorLogin + " " + (p.body ?? "").slice(-800))) near.push(item);
    else if (rnd() < 0.002) neg.push(item);
  }
}
const pick = (arr: any[], n: number) => { const seen = new Set(); const out = []; for (const x of [...arr].sort(() => rnd() - 0.5)) { if (seen.has(x.repo)) continue; seen.add(x.repo); out.push(x); if (out.length >= n) break; } return out; };
const sample: any[] = [];
for (const [k, arr] of Object.entries(bySignal)) for (const x of pick(arr, 4)) sample.push({ stratum: "match " + k, ...x });
for (const x of pick(near, 45)) sample.push({ stratum: "near-miss", ...x });
for (const x of pick(neg, 20)) sample.push({ stratum: "random", ...x });
writeFileSync(".sample.json", JSON.stringify(sample, null, 1));
console.log(Object.fromEntries(Object.entries(bySignal).map(([k, v]) => [k, v.length])), "near", near.length, "neg", neg.length, "sample", sample.length);

/** Prints the evaluation against eval/ground-truth.json and writes eval/REPORT.md. Exits 1 on any false positive. */
import { readFileSync, writeFileSync } from "node:fs";
import { registry } from "../src/core/registry";
import { evaluate, precision, type GroundTruthItem } from "./eval-lib";

const items = JSON.parse(readFileSync("eval/ground-truth.json", "utf8")) as GroundTruthItem[];
const r = evaluate(items);
const labels: Record<string, number> = {};
for (const it of items) labels[it.label] = (labels[it.label] ?? 0) + 1;
const lines = [
  `# Evaluation against hand-labelled commits and pull requests`,
  ``,
  `Generated by \`npm run eval\` with signature registry v${registry.version}. Do not edit by hand.`,
  ``,
  `${items.length} items from ${new Set(items.map((i) => i.repo)).size} repositories: ${Object.entries(labels).map(([k, v]) => `${v} ${k}`).join(", ")}.`,
  ``,
  `| | |`,
  `|---|---:|`,
  `| Correctly counted signatures | ${r.tp} |`,
  `| False positives (counted, but no signature) | ${r.fp} |`,
  `| Missed signatures | ${r.fn} |`,
  `| Counted for the wrong agent | ${r.wrongAgent} |`,
  ``,
  `## Precision per signal`,
  ``,
  `"unvalidated" means the sample holds no example of this signal yet. A high sample precision is not a guarantee for every repository.`,
  ``,
  `| Signal | Confidence | Precision |`,
  `|---|---|---:|`,
  ...r.bySignal.map((s) => `| \`${s.id}\` | ${s.confidence} | ${s.confidence === "medium" ? "not counted" : precision(s)} |`),
  ``,
  ...(r.failures.length ? [`## Failures`, ``, ...r.failures.map((f) => `- ${f.id} ${f.url}: ${f.problem}`)] : []),
];
writeFileSync("eval/REPORT.md", lines.join("\n") + "\n");
console.log(lines.slice(6, 13).join("\n"));
for (const f of r.failures) console.log(`  ${f.id} ${f.problem} ${f.url}`);
if (r.fp > 0 || r.wrongAgent > 0) process.exit(1);
